local T = require("testlib")
local test, eq, near = T.test, T.eq, T.near
local Clock = require("DD2DamageMeter/clock")

-- Mode 0 after the battle opens the end grace (3 s); the fight finishes when it runs out, with the mode 0's time.
-- Asserts an event's kind, time and outcome (outcome nil for a start).
local function expect(ev, kind, t, outcome, what)
    what = what or kind
    if not ev then error(what .. ": expected an event, got nil", 2) end
    eq(ev.kind, kind, what .. " kind")
    near(ev.t, t, 1e-9, what .. " t")
    eq(ev.outcome, outcome, what .. " outcome")
end

test("mode 2 starts, mode 0 finishes after the grace", function()
    local c = Clock.new()
    eq(c:fighting(), false, "idle at the start")
    expect(c:on_mode(10, 2, false), "start", 10)
    eq(c:fighting(), true, "fighting after start")
    eq(c:on_mode(11, 2, false), nil, "mode 2 again is not a second start")
    eq(c:on_mode(20, 0, false), nil, "mode 0 only starts the grace")
    eq(c:fighting(), true, "still fighting during the grace")
    expect(c:tick(23), "finish", 20, "end")
    eq(c:fighting(), false, "idle after finish")
    eq(c:on_mode(21, 0, false), nil, "mode 0 while idle")
    eq(c:tick(100), nil, "tick while idle")
end)

test("party hit before mode 2 starts the fight once", function()
    local c = Clock.new()
    expect(c:on_party_hit(5), "start", 5)
    eq(c:fighting(), true, "fighting after the hit")
    eq(c:on_party_hit(6), nil, "second hit does not start again")
    eq(c:on_mode(7, 2, false), nil, "mode 2 after a hit start is not a second start")
    eq(c:fighting(), true, "still the same fight")
    -- The mode took over the end of the fight: no idle timeout any more.
    eq(c:tick(60), nil, "no timeout once mode 2 was seen")
    eq(c:fighting(), true, "still fighting without hits")
    eq(c:on_mode(70, 0, false), nil, "mode 0 opens the grace")
    expect(c:tick(73), "finish", 70, "end")
end)

test("mode 1 alone does nothing", function()
    local c = Clock.new()
    eq(c:on_mode(1, 1, false), nil, "mode 1")
    eq(c:on_mode(2, 1, true), nil, "mode 1 with ending")
    eq(c:fighting(), false, "not fighting")
    eq(c:tick(100), nil, "tick")
    eq(c:on_mode(101, 0, false), nil, "mode 0 after mode 1")
end)

test("ending then mode 0 gives win", function()
    local c = Clock.new()
    expect(c:on_mode(1, 2, false), "start", 1)
    eq(c:on_mode(5, 2, true), nil, "ending is not a finish")
    eq(c:fighting(), true, "still fighting while ending")
    -- The game may drop the flag before the mode returns; the win stays.
    eq(c:on_mode(5.5, 2, false), nil, "ending flag dropped")
    eq(c:on_mode(6, 0, false), nil, "mode 0")
    expect(c:tick(9), "finish", 6, "win")
end)

test("ending and mode 0 in the same sample give win", function()
