test("ending seen before a fight does not leak into it", function()
    local c = Clock.new()
    eq(c:on_mode(1, 1, true), nil, "ending while idle")
    expect(c:on_mode(2, 2, false), "start", 2)
    c:on_mode(3, 0, false)
    expect(c:tick(6), "finish", 3, "end")
    -- A won fight does not make the next one a win either.
    c:on_mode(10, 2, false)
    c:on_mode(11, 2, true)
    c:on_mode(12, 0, false)
    expect(c:tick(15), "finish", 12, "win")
    c:on_mode(20, 2, false)
    c:on_mode(21, 0, false)
    expect(c:tick(24), "finish", 21, "end")
end)

test("hit-started fight without mode 2 times out after 10 s", function()
    local c = Clock.new()
