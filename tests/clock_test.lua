-- Asserts a resume event: the same fight goes on after a break of `gap` seconds; `by` is "mode" or "hit".
local function expect_resume(ev, t, gap, what, by)
    what = what or "resume"
    if not ev then error(what .. ": expected an event, got nil", 2) end
    eq(ev.kind, "resume", what .. " kind")
    near(ev.t, t, 1e-9, what .. " t")
    near(ev.gap, gap, 1e-9, what .. " gap")
    if by then eq(ev.by, by, what .. " by") end
end

test("a short break of the battle mode does not split the fight", function()
    local c = Clock.new()
    expect(c:on_mode(487.0, 2, false), "start", 487.0)
    eq(c:on_mode(489.238, 0, true), nil, "Normal with the ending flag: the grace opens")
    eq(c:fighting(), true, "still the same fight")
    eq(c:on_mode(489.25, 0, true), nil, "a second mode 0 keeps the first time")
    expect_resume(c:on_mode(489.269, 2, false), 489.269, 0.031, "Battle again", "mode")
    eq(c:fighting(), true, "one fight")
    eq(c:tick(500), nil, "no pending end any more, and no idle timeout once mode 2 was seen")
    -- the resume forgets the ending flag of the break: the real end is a win only if the game says so again
    eq(c:on_mode(520, 0, false), nil, "Normal")
    expect(c:tick(523), "finish", 520, "end")
    eq(c:fighting(), false, "idle after the second end")
    c = Clock.new()
    c:on_mode(487.0, 2, false)
    c:on_mode(489.238, 0, true)
    c:on_mode(489.269, 2, false)
    c:on_mode(519, 2, true)
    c:on_mode(520, 0, false)
    expect(c:tick(523), "finish", 520, "win")
end)

test("a resume forgets the ending flag, an ending flag in the grace makes the end a win", function()
    local c = Clock.new()
    c:on_mode(10, 2, true)
    c:on_mode(20, 0, false)
    expect_resume(c:on_mode(21, 2, false), 21, 1, "resume", "mode")
    c:on_mode(30, 0, false)
    expect(c:tick(33), "finish", 30, "end") -- not "win": the flag was seen before the break
    -- a resume sample that carries the flag keeps it
    c = Clock.new()
    c:on_mode(10, 2, false)
    c:on_mode(20, 0, false)
    expect_resume(c:on_mode(21, 2, true), 21, 1)
    c:on_mode(30, 0, false)
    expect(c:tick(33), "finish", 30, "win")
    -- the ending flag shows up only in the grace (mode 0, then mode 1 or 0 again with the flag)
    c = Clock.new()
    c:on_mode(10, 2, false)
    c:on_mode(20, 0, false)
    eq(c:on_mode(21, 1, true), nil, "mode 1 with the flag")
    expect(c:tick(23), "finish", 20, "win")
    c = Clock.new()
    c:on_mode(10, 2, false)
    c:on_mode(20, 0, false)
    eq(c:on_mode(21, 0, true), nil, "mode 0 again with the flag")
    expect(c:tick(23), "finish", 20, "win")
end)

test("a resume by a hit keeps the ending flag: the battle never came back to bring a new one", function()
    local c = Clock.new()
    c:on_mode(4950.6, 2, false)
    c:on_mode(4983.0, 2, true)                 -- the ending flag
    eq(c:on_mode(4985.5, 0, false), nil, "Normal, the flag already dropped")
    expect_resume(c:on_party_hit(4986.0, true), 4986.0, 0.5, "blow on a living goblin", "hit")
    eq(c:on_mode(4986.02, 0, false), nil, "the mode still reads Normal: the grace opens again")
    expect(c:tick(4989.02), "finish", 4986.02, "win")
    -- a resume by the mode still forgets the flag
    c = Clock.new()
    c:on_mode(10, 2, true)
    c:on_mode(20, 0, false)
    expect_resume(c:on_mode(21, 2, false), 21, 1, "resume", "mode")
    c:on_mode(30, 0, false)
    expect(c:tick(33), "finish", 30, "end")
end)

test("a party hit during the grace resumes the fight", function()
    local c = Clock.new()
    c:on_mode(10, 2, false)
    c:on_mode(20, 0, false)
    expect_resume(c:on_party_hit(22.5), 22.5, 2.5, "hit", "hit")
    eq(c:fighting(), true, "fighting")
    eq(c:tick(23), nil, "the end is cancelled")
    eq(c:tick(100), nil, "and stays so")
    eq(c:on_party_hit(101), nil, "a later hit is a plain hit")
    c:on_mode(110, 0, false)
    expect(c:tick(113), "finish", 110, "end")
end)

test("the grace runs out: the fight ends at the mode 0's time with its outcome", function()
    local c = Clock.new()
    c:on_mode(10, 2, false)
    c:on_mode(20, 0, false)
    eq(c:tick(22.9), nil, "2.9 s")
    eq(c:fighting(), true, "still fighting")
    expect(c:tick(23), "finish", 20, "end")
    eq(c:fighting(), false, "idle")
    eq(c:tick(30), nil, "no second finish")
    c:on_mode(40, 2, true)
    c:on_mode(50, 0, false)
    expect(c:tick(53), "finish", 50, "win")
end)

test("mode 1 keeps the end pending", function()
    local c = Clock.new()
    c:on_mode(10, 2, false)
    eq(c:on_mode(20, 0, true), nil, "mode 0")
    eq(c:on_mode(21, 1, false), nil, "mode 1")
    eq(c:fighting(), true, "still pending")
    eq(c:tick(22.9), nil, "2.9 s after mode 0")
    expect(c:tick(23), "finish", 20, "win")
    -- mode 1 after a resume does not end anything either
    c = Clock.new()
    c:on_mode(10, 2, false)
    c:on_mode(20, 0, false)
    expect_resume(c:on_mode(21, 2, false), 21, 1)
    eq(c:on_mode(22, 1, false), nil, "mode 1 in a fight")
    eq(c:tick(40), nil, "no end")
end)

test("a mode 2 or a hit after the grace is too late: the end stands", function()
    local c = Clock.new()
    c:on_mode(10, 2, false)
    c:on_mode(20, 0, false)
    expect(c:on_mode(23, 2, false), "finish", 20, "end") -- the tick of that frame comes after the mode poll
    eq(c:fighting(), false, "idle")
    expect(c:on_mode(23.02, 2, false), "start", 23.02) -- the next sample starts another fight
    c = Clock.new()
    c:on_mode(10, 2, false)
    c:on_mode(20, 0, false)
    local finished, started = c:on_party_hit(24)
    expect(finished, "finish", 20, "end")
    expect(started, "start", 24) -- the hit is not lost: it opens the next fight
    eq(c:on_party_hit(24.5), nil, "and that one goes on")
end)

test("a party hit on a new enemy in the grace ends the old fight and starts another (the deer)", function()
    local c = Clock.new()
    expect(c:on_mode(580, 2, false), "start", 580)
    c:on_party_hit(581, true)
    eq(c:on_mode(595.1, 0, true), nil, "the minotaur is dead, the battle ends")
    local finished, started = c:on_party_hit(595.4, false)
    expect(finished, "finish", 595.1, "win")
    expect(started, "start", 595.4)
    eq(c:fighting(), true, "a new fight is open")
    -- the new fight was started by a hit: the battle mode does not decide its end, the idle timeout does
    eq(c:on_mode(595.5, 0, false), nil, "mode 0 starts no grace for it")
    eq(c:tick(600), nil, "4.6 s without a hit")
    eq(c:tick(605.3), nil, "9.9 s")
    expect(c:tick(606), "finish", 606, "end")
end)

test("a party hit on an enemy of the fight in the grace resumes it", function()
    local c = Clock.new()
    c:on_mode(10, 2, false)
    c:on_mode(20, 0, false)
    expect_resume(c:on_party_hit(21, true), 21, 1, "engaged enemy", "hit")
    eq(c:fighting(), true, "same fight")
    -- no answer about the enemy counts as one of the fight
    c:on_mode(30, 0, false)
    expect_resume(c:on_party_hit(31), 31, 1, "unknown enemy", "hit")
end)

test("a party hit on a new enemy changes nothing without a pending end", function()
    local c = Clock.new()
    expect(c:on_mode(10, 2, false), "start", 10)
    eq(c:on_party_hit(12, false), nil, "a new enemy in the open fight: the fight goes on")
    eq(c:on_mode(20, 0, false), nil, "grace")
    expect(c:tick(23), "finish", 20, "end")
    expect(c:on_party_hit(30, false), "start", 30) -- idle: starts
    eq(c:on_party_hit(31, false), nil, "and a new enemy in a hit-started fight changes nothing")
    eq(c:tick(40.9), nil, "the idle timeout counts from the last hit")
    expect(c:tick(41), "finish", 41, "end")
end)

test("mode 2 in the grace resumes the fight whatever the enemy", function()
    local c = Clock.new()
    c:on_mode(10, 2, false)
    c:on_mode(20, 0, false)
    expect_resume(c:on_mode(22, 2, false), 22, 2, "mode 2", "mode")
    eq(c:fighting(), true, "same fight")
    c:on_mode(30, 0, false)
    c:on_party_hit(31, false) -- ends the fight and starts another (see above)
    eq(c:fighting(), true, "a fight is open")
end)

test("reset during the grace finishes with the pending end", function()
    local c = Clock.new()
    c:on_mode(10, 2, false)
    c:on_mode(20, 0, true)
    expect(c:reset(21), "finish", 20, "win")
    eq(c:fighting(), false, "idle")
    eq(c:tick(30), nil, "nothing left pending")
    eq(c:reset(31), nil, "reset while idle")
    -- and a reset after a resume abandons as before
    c:on_mode(40, 2, false)
    c:on_mode(41, 0, false)
    c:on_mode(42, 2, false)
    expect(c:reset(43), "finish", 43, "abandoned")
end)

test("end_grace option", function()
    local c = Clock.new({ end_grace = 1 })
    c:on_mode(10, 2, false)
    c:on_mode(20, 0, false)
    eq(c:tick(20.9), nil, "0.9 s")
    expect(c:tick(21), "finish", 20, "end")
    c = Clock.new({ end_grace = 0.5 })
    c:on_mode(10, 2, false)
    c:on_mode(20, 0, false)
    expect_resume(c:on_mode(20.4, 2, false), 20.4, 0.4)
end)

test("a hit-started fight ends by the idle timeout, not by the grace", function()
    local c = Clock.new({ end_grace = 1 })
    expect(c:on_party_hit(100), "start", 100)
    eq(c:on_mode(101, 0, false), nil, "mode 0 starts no grace")
    eq(c:tick(105), nil, "the grace would be over")
    eq(c:tick(109.9), nil, "9.9 s")
    expect(c:tick(110), "finish", 110, "end")
    -- joined by mode 2 later: the mode decides its end, with the grace
    c:on_party_hit(200)
    c:on_mode(201, 2, false)
    c:on_mode(205, 0, false)
    eq(c:tick(205.9), nil, "0.9 s")
    expect(c:tick(206), "finish", 205, "end")
end)

